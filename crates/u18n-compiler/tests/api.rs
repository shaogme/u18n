#[test]
fn locale_index_uses_normalized_string_binary_search_keys() {
    let generated = Compiler::new(CompilerOptions::default())
        .compile(CompilationInput::new(
            SourceFile::new("schema.u18n", SCHEMA_SOURCE),
            vec![
                SourceFile::new(
                    "locales/en.u18n",
                    "locale en; message app.title = \"Title\";",
                ),
                SourceFile::new(
                    "locales/fa.u18n",
                    "locale fa; message app.title = \"عنوان\";",
                ),
            ],
        ))
        .expect("both tags have cardinal plural rule resolution");
    let source = generated.source();
    let index_start = source.find("static LOCALE_INDEX").expect("locale index");
    let index_end = source
        .get(index_start..)
        .and_then(|tail| tail.find("];\n").map(|offset| index_start + offset))
        .expect("locale index terminator");
    let locale_index = source.get(index_start..index_end).expect("index range");
    let english = locale_index
        .find("locale: LocaleTag::En")
        .expect("English key");
    let persian = locale_index
        .find("locale: LocaleTag::Fa")
        .expect("Persian key");
    assert!(english < persian);
    assert!(locale_index.contains("tag: \"en\""));
    assert!(locale_index.contains("tag: \"fa\""));
    assert!(source.contains("tag: &'static str"));
    let fallback_start = source
        .rfind("pub fn fallback(locale_tag: &str)")
        .expect("fallback implementation");
    assert!(
        source
            .get(fallback_start..)
            .is_some_and(|fallback| fallback.contains("Ok(Self::En)"))
    );
    assert!(source.contains("pub enum LocaleTag {\n        En,\n        Fa,"));
    assert!(!source.contains("index: usize"));
    assert!(source.contains(
        "LOCALE_INDEX.binary_search_by(|entry| tag.cmp_ignore_ascii_case(entry.tag).reverse())"
    ));
    assert!(
        source
            .contains(".binary_search_by_key(&child_key, |entry| entry.key >> PARENT_LOCALE_BITS)")
    );
    assert!(source.contains("#[repr(u8)]\n    enum ParentLocale {"));
    assert!(source.contains("ParentLocale::from_discriminant(entry.key & PARENT_LOCALE_MASK)"));
    assert!(source.contains("    key: u64,"));
    assert!(!source.contains("parent_tag: ParentLocale"));
    assert!(source.contains("fn cldr_parent(tag: &ParsedTag<'_>) -> Option<ParentLocale>"));
}

#[test]
fn parent_index_emits_packed_numeric_keys_and_fixed_parent_discriminants() {
    let generated = Compiler::new(CompilerOptions::default())
        .compile(CompilationInput::new(
            SourceFile::new("schema.u18n", SCHEMA_SOURCE),
            vec![SourceFile::new("locales/en.u18n", ENGLISH_SOURCE)],
        ))
        .expect("valid in-memory sources should compile");
    let source = generated.source();
    let index_start = source.find("static PARENT_INDEX").expect("parent index");
    let index_end = source
        .get(index_start..)
        .and_then(|tail| tail.find("];\n").map(|offset| index_start + offset))
        .expect("parent index terminator");
    let index = source.get(index_start..index_end).expect("index range");
    let rows = index
        .lines()
        .filter_map(|line| {
            line.trim()
                .strip_prefix("ParentIndexEntry { key: ")
                .and_then(|row| row.strip_suffix(" },"))
                .and_then(|key| key.strip_suffix("u64"))
                .and_then(|key| key.parse::<u64>().ok())
        })
        .collect::<Vec<_>>();

    assert_eq!(rows.len(), 198);
    assert!(rows.windows(2).all(|pair| pair[0] < pair[1]));
    assert!(rows.iter().all(|key| *key >> 56 == 0));
    assert!((0_u64..8).all(|discriminant| rows.iter().any(|key| *key & 7 == discriminant)));
    assert!(!index.contains('"'));
    assert!(!index.contains("parent_tag"));
    assert!(!index.contains("ParentLocale::"));
    assert!(!source.contains("PARENT_INDEX_TAGS"));
    assert!(!source.contains("\"es-ar\""));
    assert!(!source.contains("\"zh-hant-mo\""));
    assert!(source.contains(
        "Root = 0,\n        En001 = 1,\n        En150 = 2,\n        Es419 = 3,\n        No = 4,\n        PtPt = 5,\n        ZhHantHk = 6,\n        EnIn = 7,"
    ));
}

