#[test]
fn interns_identical_patterns_and_emits_only_authored_fallback_bindings() {
    let schema = SourceFile::new(
        "schema.u18n",
        "schema 1; message app.common(); message app.near(); message app.title();",
    );
    let locales = || {
        vec![
            SourceFile::new(
                "locales/en.u18n",
                "locale en; message app.common = \"Same\"; message app.near = \"Near\"; message app.title = \"Title\";",
            ),
            SourceFile::new(
                "locales/fr.u18n",
                "locale fr fallback en; message app.common = \"Same\"; message app.near = \"Near!\";",
            ),
            SourceFile::new("locales/fr-CA.u18n", "locale fr-CA fallback fr;"),
            SourceFile::new(
                "locales/fr-BE.u18n",
                "locale fr-BE fallback fr-CA; message app.title = \"Titre\";",
            ),
        ]
    };
    let compiler = Compiler::new(CompilerOptions::default());
    let generated = compiler
        .compile(CompilationInput::new(
            SourceFile::new(schema.name(), schema.contents()),
            locales(),
        ))
        .expect("fallback catalogs with authored overrides should compile");
    let reordered = compiler
        .compile(CompilationInput::new(
            SourceFile::new(schema.name(), schema.contents()),
            vec![
                SourceFile::new(
                    "locales/fr-BE.u18n",
                    "locale fr-BE fallback fr-CA; message app.title = \"Titre\";",
                ),
                SourceFile::new("locales/fr-CA.u18n", "locale fr-CA fallback fr;"),
                SourceFile::new(
                    "locales/fr.u18n",
                    "locale fr fallback en; message app.common = \"Same\"; message app.near = \"Near!\";",
                ),
                SourceFile::new(
                    "locales/en.u18n",
                    "locale en; message app.common = \"Same\"; message app.near = \"Near\"; message app.title = \"Title\";",
                ),
            ],
        ))
        .expect("reordered fallback inputs should compile");
    let source = generated.source();
    let fr_ca_start = source
        .find("pub mod locale_fr_ca {")
        .expect("French Canadian module should be emitted");
    let fr_be_start = source
        .find("pub mod locale_fr_be {")
        .expect("Belgian French module should be emitted");
    let fr_ca_end = source[fr_ca_start..]
        .find("pub enum LocaleTag")
        .map(|offset| fr_ca_start + offset)
        .expect("locale modules precede the generated tag API");
    let fr_be_end = source[fr_be_start..]
        .find("pub mod locale_fr_ca {")
        .map(|offset| fr_be_start + offset)
        .expect("Canadian French module follows Belgian French");
    let fr_ca = &source[fr_ca_start..fr_ca_end];
    let fr_be = &source[fr_be_start..fr_be_end];

    let shared_store_start = source
        .find("static SHARED_STORE:")
        .expect("dynamic shared store is emitted");
    let shared_store_end = source[shared_store_start..]
        .find("pub mod locale_")
        .map(|offset| shared_store_start + offset)
        .expect("locale modules follow the shared store");
    let dynamic_store = &source[shared_store_start..shared_store_end];
    let program_count = dynamic_store
        .matches("MessageProgram { instruction_start")
        .count();
    let text_instruction_count = dynamic_store.matches("Instruction::Text").count();
    assert_eq!(program_count, 5);
    assert_eq!(text_instruction_count, 5);
    assert!(program_count < LEGACY_MESSAGE_RECORD_COUNT);
    assert!(text_instruction_count < LEGACY_TEXT_INSTRUCTION_COUNT);
    assert_eq!(dynamic_store.matches("MessageSignature {").count(), 3);
    assert_eq!(source.matches("MessageBinding { message_id").count(), 6);
    assert!(
        source.len() < PACKED_GENERATED_SOURCE_BYTES,
        "generated source has {} bytes",
        source.len()
    );
    assert!(source.contains("// output-format-version=1"));
    assert_eq!(source, reordered.source());
    assert!(source.contains("pub static __MESSAGE_DATA_0: MessageData"));
    assert!(source.contains("LocaleProgram { locale_tag: \"fr-CA\", program_id:"));
    assert!(!source.contains("MESSAGE_DATA: &[MessageData"));
    assert!(fr_ca.contains("fallback: Some(&super::locale_fr::CATALOG)"));
    assert!(fr_ca.contains("bindings: &[]"));
    assert!(fr_be.contains("fallback: Some(&super::locale_fr_ca::CATALOG)"));
    assert!(fr_be.contains("MessageBinding { message_id: 2, program_id:"));
    assert!(!fr_be.contains("MessageBinding { message_id: 0,"));
    assert!(!fr_be.contains("MessageBinding { message_id: 1,"));
}

#[test]
fn coverage_accepts_complete_and_missing_catalogs() {
    let compiler = Compiler::new(CompilerOptions::default());
    let complete = compiler
        .coverage(CompilationInput::new(
            SourceFile::new("schema.u18n", SCHEMA_SOURCE),
            vec![SourceFile::new("locales/en.u18n", ENGLISH_SOURCE)],
        ))
        .expect("complete catalog coverage should succeed");
    let missing_input = CompilationInput::new(
        SourceFile::new("schema.u18n", SCHEMA_SOURCE),
        vec![SourceFile::new("locales/en.u18n", "locale en;\n")],
    );
    let missing = compiler
        .coverage(missing_input)
        .expect("coverage should report missing messages");
    let missing_compile = compiler
        .compile(CompilationInput::new(
            SourceFile::new("schema.u18n", SCHEMA_SOURCE),
            vec![SourceFile::new("locales/en.u18n", "locale en;\n")],
        ))
        .err()
        .expect("incomplete catalog should fail compilation");

    assert!(complete.contains("\"authored\": 1"));
    assert!(complete.contains("\"missing\": 0"));
    assert!(missing.contains("\"status\": \"missing\""));
    assert!(missing.contains("\"missing\": 1"));
    assert!(
        missing_compile
            .to_string()
            .contains("is missing schema key")
    );
}

