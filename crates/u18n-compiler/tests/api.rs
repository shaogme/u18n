#[test]
fn atomic_locale_options_require_an_exact_input_fallback() {
    let locales = || {
        vec![
            SourceFile::new("locales/en.u18n", ENGLISH_SOURCE),
            SourceFile::new(
                "locales/fr.u18n",
                "locale fr;\nmessage app.title = \"Titre\";\n",
            ),
        ]
    };
    let missing_fallback = Compiler::new(CompilerOptions::default().with_atomic_locale(true))
        .compile(CompilationInput::new(
            SourceFile::new("schema.u18n", SCHEMA_SOURCE),
            locales(),
        ))
        .err()
        .expect("atomic compilation should require a final fallback");
    assert!(
        missing_fallback
            .to_string()
            .contains("requires a final fallback locale")
    );

    let non_atomic_fallback =
        Compiler::new(CompilerOptions::default().with_final_fallback_locale("en"))
            .compile(CompilationInput::new(
                SourceFile::new("schema.u18n", SCHEMA_SOURCE),
                locales(),
            ))
            .err()
            .expect("non-atomic compilation should reject a final fallback");
    assert!(
        non_atomic_fallback
            .to_string()
            .contains("only be configured")
    );

    let wrong_case = Compiler::new(
        CompilerOptions::default()
            .with_atomic_locale(true)
            .with_final_fallback_locale("EN"),
    )
    .compile(CompilationInput::new(
        SourceFile::new("schema.u18n", SCHEMA_SOURCE),
        locales(),
    ))
    .err()
    .expect("atomic compilation should match the fallback tag exactly");
    assert!(wrong_case.to_string().contains("`EN`"));
    assert!(
        wrong_case
            .to_string()
            .contains("exactly match an input catalog")
    );

    let generated = Compiler::new(
        CompilerOptions::default()
            .with_atomic_locale(true)
            .with_final_fallback_locale("en"),
    )
    .compile(CompilationInput::new(
        SourceFile::new("schema.u18n", SCHEMA_SOURCE),
        locales(),
    ))
    .expect("an exact input fallback should compile");
    assert!(generated.source().contains("atomic-locale-selection=true"));
    assert!(generated.source().contains("final-fallback-locale=en"));
    assert!(generated.source().contains("FINAL_FALLBACK_LOCALE"));
    assert!(generated.source().contains("AtomicPtr<Locale>"));
    assert!(
        generated
            .source()
            .contains("FINAL_FALLBACK_CATALOG: &Catalog")
    );
    assert!(
        generated
            .source()
            .contains("pub fn current_catalog() -> &'static Catalog")
    );
    assert!(!generated.source().contains("__u18n_current_catalog"));
    assert!(generated.source().contains("macro_rules! t"));
    assert!(generated.source().contains("m_app_stitle"));
    assert!(generated.source().contains("target_has_atomic = \"ptr\""));
}

#[test]
fn fingerprints_cover_atomic_fallback_and_pool_generation_options() {
    let schema = SourceFile::new("schema.u18n", SCHEMA_SOURCE);
    let locale_sources = || {
        vec![
            SourceFile::new("locales/en.u18n", ENGLISH_SOURCE),
            SourceFile::new(
                "locales/fr.u18n",
                "locale fr;\nmessage app.title = \"Titre\";\n",
            ),
        ]
    };
    let default = Compiler::new(CompilerOptions::default())
        .compile(CompilationInput::new(
            SourceFile::new(schema.name(), schema.contents()),
            locale_sources(),
        ))
        .expect("default generation should succeed");
    let pool_changed = Compiler::new(CompilerOptions::default().with_pool_limit(0))
        .compile(CompilationInput::new(
            SourceFile::new(schema.name(), schema.contents()),
            locale_sources(),
        ))
        .expect("pool-limited generation should succeed");
    let atomic_en = Compiler::new(
        CompilerOptions::default()
            .with_atomic_locale(true)
            .with_final_fallback_locale("en"),
    )
    .compile(CompilationInput::new(
        SourceFile::new(schema.name(), schema.contents()),
        locale_sources(),
    ))
    .expect("atomic generation with English fallback should succeed");
    let atomic_fr = Compiler::new(
        CompilerOptions::default()
            .with_atomic_locale(true)
            .with_final_fallback_locale("fr"),
    )
    .compile(CompilationInput::new(
        SourceFile::new(schema.name(), schema.contents()),
        locale_sources(),
    ))
    .expect("atomic generation with French fallback should succeed");

    let default_fingerprint =
        input_fingerprint(default.source()).expect("default fingerprint should be emitted");
    assert_ne!(
        default_fingerprint,
        input_fingerprint(pool_changed.source()).expect("pool fingerprint should be emitted")
    );
    assert_ne!(
        default_fingerprint,
        input_fingerprint(atomic_en.source()).expect("atomic fingerprint should be emitted")
    );
    assert_ne!(
        input_fingerprint(atomic_en.source()),
        input_fingerprint(atomic_fr.source())
    );
    assert!(pool_changed.source().contains("pool-limit=0"));
    assert!(atomic_fr.source().contains("final-fallback-locale=fr"));
}
