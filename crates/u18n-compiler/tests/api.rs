use u18n_compiler::{CompilationInput, Compiler, CompilerOptions, SourceFile};

const SCHEMA_SOURCE: &str = "schema 1;\nmessage app.title();\n";
const ENGLISH_SOURCE: &str = "locale en;\nmessage app.title = \"Title\";\n";
const PACKED_GENERATED_SOURCE_BYTES: usize = 29_000;
const LEGACY_MESSAGE_RECORD_COUNT: usize = 12;
const LEGACY_TEXT_INSTRUCTION_COUNT: usize = 12;

fn input_fingerprint(source: &str) -> Option<&str> {
    source
        .lines()
        .find_map(|line| line.strip_prefix("// input-sha256="))
}

#[test]
fn compiles_named_in_memory_sources_and_reports_pool_statistics() {
    let input = CompilationInput::new(
        SourceFile::new("schema.u18n", SCHEMA_SOURCE),
        vec![SourceFile::new("locales/en.u18n", ENGLISH_SOURCE)],
    );
    let generated = Compiler::new(CompilerOptions::default())
        .compile(input)
        .expect("valid in-memory sources should compile");

    assert!(generated.source().contains("Generated by u18n compiler"));
    assert!(generated.source().contains("pub mod locale_en"));
    assert!(generated.source().contains("macro_rules! t"));
    assert!(generated.source().contains("atomic-locale-selection=false"));
    assert!(generated.source().contains("final-fallback-locale="));
    assert!(generated
        .source()
        .contains("cldr-cardinal-rules-sha256=69a30c57a621de9c52ec6ca95fe7bf9f06df6f8c13ca71a72e447b532c92cff7"));
    assert!(generated
        .source()
        .contains("cldr-supplemental-data-sha256=745150ec1408d50e1a272b65654a5dd645f3e60f5cc2898b576f725b28538d1a"));
    assert!(generated.source().contains(
        "cldr-aliases-sha256=b06614fc2c9aab3b9a9f7e8bf9328f4f7a95d89b2d2dbb300d0caff0f885c164"
    ));
    assert!(
        generated
            .source()
            .contains("pub fn fallback(locale_tag: &str) -> Result<Self, &'static str>")
    );
    assert!(generated.source().contains("pool-limit=256"));
    assert_eq!(
        input_fingerprint(generated.source()),
        Some("f06ec0540e33c0c26ed402a908cbd96be0c1ed5068f9483217de1d04ca8a624e")
    );
    assert!(!generated.source().contains("AtomicPtr<Catalog>"));
    assert!(generated.pool_statistics().literal_fragments() > 0);
    assert!(generated.pool_statistics().pool_bytes() > 0);
    assert!(generated.pool_statistics().overlap_optimization_enabled());
    assert_eq!(generated.pool_statistics().keyed_shard_count(), 1);
    assert!(generated.pool_statistics().keyed_literal_fragments() > 0);
    assert!(generated.pool_statistics().keyed_pool_bytes() > 0);
}

